SQL v/s NoSQL



SQL:  Yaha Jo hamra Data Hota hai Wo Tables Ke form me store hota hai 
Relational Database (data stored in Tables)
eg - MySQL(Sabse Popular), Oracle, PostgreSQL etc.



NoSQL: Collection of data base  Yani Enke Andhr ek Common property hai ki Ye SQL use nahi karte hai , Aur Ye bahot sare data bse ke collection hai ye ek data base nahi hota hai esliye inhe haam non relational data bse bolte ha yani ese data bases jo tables ke form me data ko store nahi karte hai kissi aur formate me kar sakte hai but row , column me nahi karte hai 
Non Relational Database (data stored in document/key-val/graphs etc.)
eg - MongoDb(Esme Se sabse Popular hota hai ye Mongo-DB), Cassandra, Neo4j etc.

