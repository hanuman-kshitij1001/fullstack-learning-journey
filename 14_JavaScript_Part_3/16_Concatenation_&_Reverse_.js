//  Array Methods

 let primary = ["red", "yellow", "blue"];
 let secondary = ["orange", "green", "violet"];


//→concat: merge 2 arrays
primary.concat(secondary); /// (6) ['red', 'yellow', 'blue', 'orange', 'green', 'violet']

//→reverse: reverse an array
primary.reverse();  //: Output:  (3) ['blue', 'yellow', 'red']

