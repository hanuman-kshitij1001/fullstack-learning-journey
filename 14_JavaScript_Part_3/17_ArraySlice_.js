// Array Methods
// slice: copies a portion of an array

let colors = ["red", "yellow", "blue", "orange", "pink", "white"];

colors.slice();        // Eska Matlb hai hame Pura ka pura Array Chahiye Bhai         // (6) ['red', 'yellow', 'blue', 'orange', 'pink', 'white']

colors.slice(2)       // Single value Means Only Use Starting to End                 //  (4)  ['blue', 'orange', 'pink','white'];

colors.slice(2, 3);  // Staring to End but we can not include Ending Ok             //     ['blue']

colors.slice(-2);   // (2)  ['pink', 'white']

colors.slice(10);   //  [] kahali box ayega hamre pass 

 